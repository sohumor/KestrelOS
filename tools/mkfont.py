#!/usr/bin/env python3
"""Generate kernel/font.c -- KestrelOS' 8x16 console bitmap font.

The font is designed here, by hand, as ASCII art: one block per glyph,
one line per scanline, '#' = ink and '.' = paper.  Nothing is imported
from an existing typeface.

Cell geometry
-------------
The C array stores 8 pixels per row (bit 7 = leftmost pixel), but the
art below is only 6 columns wide: the generator adds one blank column
of side bearing on each side, so glyphs never touch horizontally.

Vertical metrics (row indices into the 16-row cell):

    row  0 - 1   leading
    row  2       cap line / ascender line
    row  5       x-height line
    row 11       baseline row (last row of a non-descending glyph)
    row 12 - 14  descender zone
    row 15       leading

    cap height 10px, x-height 7px, descender 3px, stroke weight 1px.

Trailing all-blank rows may be omitted from a block; the generator pads
them.  Every block is validated for size and alphabet before emission.

Usage
-----
    python3 tools/mkfont.py                  # write kernel/font.c
    python3 tools/mkfont.py --dump           # ASCII proof sheet
    python3 tools/mkfont.py --dump 'Ag@'     # ASCII proof of some glyphs
    python3 tools/mkfont.py --png sheet.png  # rendered proof sheet
"""

