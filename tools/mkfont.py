# --------------------------------------------------------------------------
# Art -> bitmap
# --------------------------------------------------------------------------

def parse(art, what):
    """Turn one ASCII-art block into 16 bytes (bit 7 = leftmost pixel)."""
    rows = [r for r in art.split("\n") if r != ""]
    if len(rows) > CELL_H:
        raise ValueError(f"{what}: {len(rows)} rows, at most {CELL_H} allowed")
    rows += ["." * ART_W] * (CELL_H - len(rows))

    out = []
    for y, row in enumerate(rows):
        if len(row) != ART_W:
            raise ValueError(f"{what} row {y}: width {len(row)}, want {ART_W}")
        bits = 0
        for x, ch in enumerate(row):
            if ch == "#":
                bits |= 1 << (CELL_W - 1 - BEARING - x)
            elif ch != ".":
                raise ValueError(f"{what} row {y}: bad character {ch!r}")
        out.append(bits)
    return out


def build():
    """Return (list of 95 glyph bitmaps, fallback bitmap)."""
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if ch not in GLYPHS:
            raise ValueError(f"no glyph designed for {ch!r} (0x{code:02X})")
        glyphs.append(parse(GLYPHS[ch], f"{ch!r} (0x{code:02X})"))
    extra = sorted(c for c in GLYPHS if not FIRST <= ord(c) <= LAST)
    if extra:
        raise ValueError(f"glyphs outside the covered range: {extra}")
    return glyphs, parse(FALLBACK, "fallback")


# --------------------------------------------------------------------------
# Emitters
# --------------------------------------------------------------------------

BANNER = ("/* Generated by tools/mkfont.py -- do not edit by hand.\n"
          " *\n"
          " * KestrelOS' own 8x16 console face: cap height 10, x-height 7,\n"
          " * descender 3, one pixel of side bearing on each side.\n"
          " */\n")


def emit_c(path, glyphs, fallback):
    lines = [BANNER.rstrip("\n"), "", '#include "font.h"', "",
             "const uint8_t font8x16[95][16] = {"]
    for i, g in enumerate(glyphs):
        ch = chr(FIRST + i)
        shown = "\\\\" if ch == "\\" else ch
        lines.append(f"    /* 0x{FIRST + i:02X}  '{shown}' */")
        lines.append("    { " + ", ".join(f"0x{b:02X}" for b in g) + " },")
    lines.append("};")
    lines.append("")
    lines.append("/* Drawn in place of any code point outside 0x20..0x7E. */")
    lines.append("const uint8_t font8x16_fallback[16] = {")
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in fallback))
    lines.append("};")
    lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"mkfont: wrote {path} ({len(glyphs)} glyphs)")


def dump(glyphs, fallback, which):
    """Print the glyphs as ASCII art, exactly as the kernel will draw them."""
    items = []
    if which:
        for ch in which:
            if FIRST <= ord(ch) <= LAST:
                items.append((f"0x{ord(ch):02X} '{ch}'", glyphs[ord(ch) - FIRST]))
    else:
        items = [(f"0x{FIRST + i:02X} '{chr(FIRST + i)}'", g)
                 for i, g in enumerate(glyphs)]
        items.append(("fallback", fallback))

    per_line = 8
    for base in range(0, len(items), per_line):
        chunk = items[base:base + per_line]
        print("  ".join(f"{name:<10}" for name, _ in chunk))
        for y in range(CELL_H):
            cells = []
            for _, g in chunk:
                bits = "".join("#" if g[y] & (0x80 >> x) else "."
                               for x in range(CELL_W))
                cells.append(f"{bits:<10}")
            print("  ".join(cells))
        print()


def emit_png(path, glyphs, fallback, scale=3):
    """Render a proof sheet: the whole face plus a pangram, as a PNG."""
    cols = 16
    rows = (len(glyphs) + cols - 1) // cols
    sample = ["ABCDEFGHIJKLMNOPQRSTUVWXYZ",
              "abcdefghijklmnopqrstuvwxyz",
              "0123456789 !\"#$%&'()*+,-./",
              ":;<=>?@[\\]^_`{|}~",
              "The quick brown fox jumps",
              "over the lazy dog. {kfs}",
              "0O1lI| g/q/p/y  8B 5S 2Z"]
    sw = max(len(s) for s in sample)

    gw, gh = CELL_W + 1, CELL_H + 1
    w = max(cols * gw + 1, sw * CELL_W + 2)
    h = rows * gh + 1 + 6 + len(sample) * CELL_H + 2
    px = bytearray(w * h)          # 1 = ink

    def blit(glyph, ox, oy):
        for y in range(CELL_H):
            for x in range(CELL_W):
                if glyph[y] & (0x80 >> x):
                    iy, ix = oy + y, ox + x
                    if 0 <= ix < w and 0 <= iy < h:
                        px[iy * w + ix] = 1

    for i, g in enumerate(glyphs + [fallback]):
        blit(g, (i % cols) * gw + 1, (i // cols) * gh + 1)

    top = rows * gh + 7
    for r, line in enumerate(sample):
        for c, ch in enumerate(line):
            g = glyphs[ord(ch) - FIRST] if FIRST <= ord(ch) <= LAST else fallback
            blit(g, 1 + c * CELL_W, top + r * CELL_H)

    def chunk(tag, data):
        body = tag + data
        return (struct.pack(">I", len(data)) + body
                + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF))

    raw = bytearray()
    for y in range(h):
        row = bytearray()
        for x in range(w):
            v = 0x14 if px[y * w + x] else 0xF2
            row += bytes((v, v, v)) * scale
        for _ in range(scale):
            raw.append(0)
            raw += row
    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR",
                   struct.pack(">IIBBBBB", w * scale, h * scale, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
           + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    print(f"mkfont: wrote {path} ({w * scale}x{h * scale}, {scale}x)")


def main():
    args = sys.argv[1:]
    glyphs, fallback = build()

    if args and args[0] == "--dump":
        dump(glyphs, fallback, args[1] if len(args) > 1 else None)
        return 0
    if args and args[0] == "--png":
        if len(args) < 2:
            print("usage: mkfont.py --png out.png")
            return 1
        emit_png(args[1], glyphs, fallback)
        return 0
    if args:
        print(__doc__)
        return 1

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    emit_c(os.path.join(root, "kernel", "font.c"), glyphs, fallback)
    return 0


if __name__ == "__main__":
    sys.exit(main())
