static int g_pass = 0;
static int g_fail = 0;

static void check_cond(int ok, const char *name, const char *detail)
{
    if (ok) {
        g_pass++;
    } else {
        g_fail++;
        fprintf(stderr, "FAIL: %s (%s)\n", name, detail ? detail : "");
    }
}

static int max_channel_diff(const uint32_t *a, const uint32_t *b, size_t n)
{
    int maxd = 0;
    size_t i;

    for (i = 0; i < n; i++) {
        int s;
        for (s = 0; s <= 16; s += 8) {
            int ca = (int)((a[i] >> s) & 0xffu);
            int cb = (int)((b[i] >> s) & 0xffu);
            int d = ca > cb ? ca - cb : cb - ca;
            if (d > maxd)
                maxd = d;
        }
    }
    return maxd;
}

static void test_reference_match(const char *name, const uint8_t *jpg, size_t len,
                                 int ew, int eh, const uint32_t *ref, int tol,
                                 int check_gray)
{
    struct img_info info;
    struct image im;
    struct image via_img;
    int rc;

    rc = img_probe(jpg, (unsigned long)len, &info);
    check_cond(rc == IMG_OK && info.fmt == IMG_FMT_JPEG &&
               info.w == ew && info.h == eh, name, "img_probe");

    rc = jpeg_decode(jpg, (unsigned long)len, &im);
    check_cond(rc == IMG_OK && im.px != NULL && im.w == ew && im.h == eh &&
               !im.has_alpha && im.alpha == NULL, name, "jpeg_decode");
    if (rc == IMG_OK && im.px != NULL) {
        size_t n = (size_t)ew * (size_t)eh;
        int maxd = max_channel_diff(im.px, ref, n);
        check_cond(maxd <= tol, name, "pixel diff within tolerance");
        if (check_gray) {
            size_t i;
            int gray_ok = 1;
            for (i = 0; i < n; i++) {
                uint32_t p = im.px[i];
                if (((p >> 16) & 0xffu) != ((p >> 8) & 0xffu) ||
                    ((p >> 8) & 0xffu) != (p & 0xffu)) {
                    gray_ok = 0;
                    break;
                }
            }
            check_cond(gray_ok, name, "grayscale RGB channels identical");
        }
    }

    rc = img_decode(jpg, (unsigned long)len, &via_img);
    check_cond(rc == IMG_OK && via_img.px != NULL && im.px != NULL &&
               memcmp(via_img.px, im.px, (size_t)ew * (size_t)eh * sizeof(uint32_t)) == 0,
               name, "img_decode matches jpeg_decode");

    img_free(&via_img);
    img_free(&im);
}

static void test_prog_vs_base_pair(const char *name,
                                   const uint8_t *pjpg, size_t plen,
                                   const uint8_t *bjpg, size_t blen,
                                   int ew, int eh)
{
    struct img_info pinfo, binfo;
    struct image pim, bim;
    int rp, rb;

    rp = img_probe(pjpg, (unsigned long)plen, &pinfo);
    rb = img_probe(bjpg, (unsigned long)blen, &binfo);
    check_cond(rp == IMG_OK && rb == IMG_OK &&
               pinfo.fmt == IMG_FMT_JPEG && binfo.fmt == IMG_FMT_JPEG &&
               pinfo.w == ew && binfo.w == ew && pinfo.h == eh && binfo.h == eh,
               name, "probe prog & base");

    rp = jpeg_decode(pjpg, (unsigned long)plen, &pim);
    rb = jpeg_decode(bjpg, (unsigned long)blen, &bim);
    check_cond(rp == IMG_OK && rb == IMG_OK &&
               pim.w == ew && pim.h == eh && bim.w == ew && bim.h == eh &&
               pim.px != NULL && bim.px != NULL,
               name, "decode prog & base");
    if (rp == IMG_OK && rb == IMG_OK && pim.px && bim.px) {
        int maxd = max_channel_diff(pim.px, bim.px, (size_t)ew * (size_t)eh);
        check_cond(maxd <= 1, name, "progressive output matches baseline output");
    }
    img_free(&pim);
    img_free(&bim);
}

static void test_truncated_prefixes(const char *name, const uint8_t *jpg, size_t len)
{
    uint8_t *buf = (uint8_t *)malloc(len);
    size_t k;
    int all_rejected = 1;

    check_cond(buf != NULL, name, "alloc truncation scratch");
    if (!buf)
        return;

    for (k = 0; k < len; k++) {
        struct image im;
        int rc;
        if (k > 0)
            memcpy(buf, jpg, k);
        rc = jpeg_decode(k == 0 ? jpg : buf, (unsigned long)k, &im);
        if (rc == IMG_OK || im.px != NULL || im.alpha != NULL) {
            fprintf(stderr, "FAIL: %s truncated at %lu/%lu unexpectedly returned %d\n",
                    name, (unsigned long)k, (unsigned long)len, rc);
            img_free(&im);
            all_rejected = 0;
            break;
        }
    }
    check_cond(all_rejected, name, "all truncated prefixes fail cleanly");
    free(buf);
}

