#pragma once

/* libgui - the KestrelOS userspace GUI toolkit.
 *
 * A window is a rectangle of 32-bit 0x00RRGGBB pixels that the kernel
 * compositor maps into this process (see SYS_WIN_* in abi/kestrel_abi.h).
 * Drawing is a plain memory write into that buffer; gui_flush() publishes
 * it. Nothing here talks to the compositor except gui.c, so an app only
 * ever sees gui_* calls and struct k_event.
 *
 * Layers:
 *   gui.c       windows, the event loop, syscall wrappers, small helpers
 *   draw.c      clipped drawing primitives, text, the colour arithmetic
 *   widgets.c   buttons, labels, text boxes, lists, menus, scrollbars
 *   font_data.c the 8x16 face, generated by libgui/mkfont_user.py
 *
 * Every drawing call clips to the window and to the current clip
 * rectangle, so passing out-of-range coordinates is safe, never fatal.
 */

#include <stdint.h>
#include <kestrel.h>

/* ---------------------------------------------------------------- font */

#define GUI_FONT_W 8
#define GUI_FONT_H 16

