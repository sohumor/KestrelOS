/* bg argument to the text calls: >= 0 is a colour, this is "leave the
 * pixels behind the glyph alone". */
#define GUI_TRANSPARENT (-1L)

/* --------------------------------------------------------------- window */

typedef struct gui_rc {
    int x, y, w, h;
} gui_rc;

typedef struct gui_window {
    uint32_t wid;        /* compositor window id                    */
    int w, h;            /* client size actually granted            */
    uint32_t *px;        /* w*h pixels, tightly packed, row-major   */
    int open;            /* 0 once closed or the compositor is gone */
    gui_rc clip;         /* current clip rectangle, window coords   */
} gui_window;

static inline gui_rc gui_mkrc(int x, int y, int w, int h)
{
    gui_rc r;

    r.x = x;
    r.y = y;
    r.w = w;
    r.h = h;
    return r;
}

/* Screen geometry. Returns 0 and fills the outputs, or -1 when the machine
 * booted without a linear framebuffer (in which case gui_open always
 * fails and an app should print an error and exit rather than spin). */
int gui_screen(int *w, int *h);

/* Create a window. flags is 0 or a mix of K_WIN_NODECOR/K_WIN_DESKTOP.
 * Returns NULL if there is no framebuffer, no compositor, or no room. */
gui_window *gui_open(const char *title, int x, int y, int w, int h,
                     unsigned flags);
void gui_close(gui_window *win);

/* Publish the pixel buffer. Returns 0, or -1 if the window is gone
 * (which also clears win->open, so event loops fall out). */
int gui_flush(gui_window *win);
int gui_move(gui_window *win, int x, int y);
int gui_window_list(int index, struct k_winsummary *out);
int gui_window_control(uint32_t wid, int action);

/* Wait up to timeout_ms for an event: 1 = *ev filled, 0 = timed out,
 * -1 = the window/compositor is gone (win->open is cleared). A timeout
 * of 0 polls. */
int gui_next_event(gui_window *win, struct k_event *ev, int timeout_ms);

/* Simple event loop. `fn` is called for every event and, when tick_ms is
 * positive, once per idle tick with an event of type KEV_NONE; returning
 * non-zero from it stops the loop. KEV_CLOSE is delivered to the handler
 * first and then always stops the loop. Returns the handler's last value,
 * or -1 if the window died under it. */
typedef int (*gui_handler)(gui_window *win, const struct k_event *ev,
                           void *ctx);
int gui_run(gui_window *win, gui_handler fn, void *ctx, int tick_ms);

