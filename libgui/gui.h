/* Fixed-point trigonometry: the angle is in tenths of a degree (3600 =
 * one turn) and the result is Q16, i.e. -65536..65536. There is no libm
 * and no FPU dependency; this is a Taylor series in 64-bit integers. */
#define GUI_TURN 3600
#define GUI_Q16  65536
int gui_sin_q16(int tenths_deg);
int gui_cos_q16(int tenths_deg);

/* ------------------------------------------------- widgets (widgets.c) */

/* Input state folded out of the event stream. Call gui_ui_begin() at the
 * top of a frame, gui_ui_event() for every event you pump, then draw the
 * widgets; they consume the one-shot fields (down/up/key). */
typedef struct gui_ui {
    int mx, my;                  /* pointer, client coordinates      */
    unsigned buttons;            /* buttons currently held           */
    int down, up;                /* a press/release happened         */
    unsigned down_btn, up_btn;   /* which buttons those carried      */
    int down_x, down_y;
    int up_x, up_y;
    int dbl;                     /* the release completed a double click */
    int key;                     /* key this frame, 0 = none         */
    int wheel;                   /* wheel steps, + = away from user  */
    unsigned long last_click_ms; /* internal: double-click timing    */
    int last_click_x, last_click_y;
} gui_ui;

void gui_ui_begin(gui_ui *ui);
void gui_ui_event(gui_ui *ui, const struct k_event *ev);
int gui_hit(gui_rc r, int x, int y);

/* A push button; returns 1 on the frame the click completes inside it. */
int gui_button(gui_window *win, gui_rc r, const char *label, gui_ui *ui);
/* enabled = 0 greys it out and never returns 1; active = 1 draws it as a
 * latched/selected button. */
int gui_button_ex(gui_window *win, gui_rc r, const char *label, gui_ui *ui,
                  int enabled, int active);
int gui_icon_button(gui_window *win, gui_rc r, enum gui_icon icon,
                    const char *label, gui_ui *ui, int enabled, int active);

void gui_label(gui_window *win, int x, int y, const char *s, uint32_t fg);

